import { EmailVerificationPage, ForgotPasswordPage, ResetPasswordPage, ResendVerificationPage } from './pages/account/AuthUtilityPages';
import { NewAnnonce } from './pages/public/NewAnnonce';
import { NotFound } from './pages/NotFound';
import { AdminDashboard } from './pages/admin/AdminDashboard';
import { getAppPath } from './utils/appBasePath';

export function Router(){
 const path=getAppPath(window.location.pathname);
 let page;
 if(path==='/admin' || path==='/admin/utilisateurs' || path==='/admin/litiges' || path==='/admin/payouts') page = <AdminDashboard/>;
 else if(path==='/connexion') page = <AuthPage mode="login"/>;
 else if(path==='/inscription') page = <AuthPage mode="register"/>;
 else if(path==='/verification-email') page = <EmailVerificationPage/>;
 else if(path==='/verification-email/renvoyer') page = <ResendVerificationPage/>;
 else if(path==='/mot-de-passe-oublie') page = <ForgotPasswordPage/>;
 else if(path==='/reset-password') page = <ResetPasswordPage/>;
 else if(path==='/profil') page = <ProfilePage/>;
 else if(path==='/litiges') page = <SupportPage/>;
 else if(path==='/remboursements') page = <RefundsPage/>;
 else if(path==='/mes-annonces') page = <MyListingsPage/>;
 else if(path.startsWith('/reservation/')) page = <ReservationDetailPage/>;
 else if(path==='/favoris') page = <FavoritesPage/>;
 else if(path==='/notifications') page = <NotificationsPage/>;
 else if(path==='/activites' || path==='/app') page = path==='/app' ? <Home/> : <ActivitiesPage/>;
 else if(path==='/annonces/nouvelle') page = <NewAnnonce/>;
 else if(path==='/messages') page = <Messages/>;
 else if(path==='/recherche') page = <SearchPage/>;
 else if(path==='/categories') page = <CategoriesPage/>;
 else if(path==='/boutiques') page = <DirectoryPage kind="boutiques"/>;
 else if(path==='/restaurants') page = <DirectoryPage kind="restaurants"/>;
 else if(path==='/hotels') page = <DirectoryPage kind="hotels"/>;
 else if(path==='/livreurs') page = <DirectoryPage kind="livreurs"/>;
 else if(path==='/pro') page = <ProfessionalOverview/>;
 else if(path==='/pro/nouvelle-activite') page = <ProfessionalOnboarding/>;
 else if(path==='/pro/commandes') page = <ProfessionalOrders/>;
 else if(path==='/pro/clients') page = <ProfessionalContacts/>;
 else if(path==='/pro/messages') page = <Messages/>;
 else if(path==='/pro/finances') page = <ProfessionalFinance/>;
 else if(path==='/pro/abonnement') page = <ProfessionalSubscription/>;
 else if(path==='/pro/parametres') page = <ProfessionalSettings/>;
 else if(path==='/pro/livraisons/groupees') page = <GroupedDeliveryPage/>;
 else if(path==='/pro/livraisons') page = <ProfessionalDeliveryManager/>;
 else if(path==='/pro/livraisons/agence') page = <DeliveryAgency/>;
 else if(path==='/pro/livraisons/boutique') page = <BoutiqueDeliveryManager/>;
 else if(path==='/pro/livraisons/restaurant') page = <RestaurantDeliveryManager/>;
 else if(path==='/pro/reservations') { const reservationType=new URLSearchParams(window.location.search).get('espaceType'); page = reservationType==='restauration' ? <RestaurantReservationManager/> : reservationType==='hotel' ? <HotelDashboard initialTab="reservations"/> : <ProfessionalReservationsHub/>; }
 else if(path==='/pro/vitrine') page = <StorefrontBuilder/>;
 else if(path==='/pro/catalogue') { const kind=new URLSearchParams(window.location.search).get('espaceType'); page = kind==='restauration' ? <RestaurantMenuManager/> : kind==='hotel' ? <HotelDashboard/> : <BoutiqueCatalogManager/>; }
 else if(path==='/pro/hotel') page = <HotelDashboard/>;
 else if(/^\/restaurant\/[^/]+\/reserver$/.test(path)) page = <RestaurantReservation/>;
 else if(/^\/hotel\/[^/]+\/reserver$/.test(path)) page = <HotelBooking/>;
 else if(path==='/livraison') page = <DeliveryOptions/>;
 else if(path==='/panier') page = <Cart/>;
 else if(path==='/checkout') page = <Checkout/>;
 else if(path.startsWith('/commande/')) page = <Order/>;
 else if(path.startsWith('/livraison/')) page = <Delivery/>;
 else if(path.startsWith('/annonce/') || path.startsWith('/service/')) page = <AnnonceDetail/>;
 else if(path.startsWith('/plat/')) page = <PublicPlat/>;
 else if(path.startsWith('/produit/')) page = <PublicProduct productId={path.split('/')[2] || ''}/>;
 else if(path.startsWith('/livreur/')) page = <PublicCourier/>;
 else if(/^\/vitrine\/[^/]+$/.test(path)) page = <PublicStorefront slug={path.split('/')[2]}/>;
 else if(/^\/boutique\/[^/]+$/.test(path)) page = <PublicStorefront type="boutique" spaceId={path.split('/')[2]}/>;
 else if(/^\/restaurant\/[^/]+$/.test(path)) page = <PublicStorefront type="restaurant" spaceId={path.split('/')[2]}/>;
 else if(/^\/hotel\/[^/]+$/.test(path)) page = <PublicStorefront type="hotel" spaceId={path.split('/')[2]}/>;
 else if(path==='/') page = <Home/>;
 else page = <NotFound/>;
 return <PageTransition key={path}>{page}</PageTransition>;
}
