import { Directory } from './pages/public/Directory';
import { ResetPasswordPage, ResendVerificationPage, VerifyEmailPage } from './pages/AccountFlows';
import { appPath } from './utils/navigation';

export function Router(){
 const path=window.location.pathname.replace(/^\/Loka(?=\/|$)/, '') || '/';
 let page;
 if(path==='/mot-de-passe-oublie') page = <ForgotPasswordPage/>;
 else if(path==='/verification-email') page = <VerifyEmailPage/>;
 else if(path==='/reset-password') page = <ResetPasswordPage/>;
 else if(path==='/renvoyer-confirmation') page = <ResendVerificationPage/>;
 else if(path==='/connexion') page = <AuthPage mode="login"/>;
 else if(path==='/inscription') page = <AuthPage mode="register"/>;
 else if(path==='/profil') page = <ProfilePage/>;
 else if(path==='/mon-espace') page = <MySpacePage/>;
 else if(path==='/publier-annonce') page = <PublishAnnouncementPage/>;
 else if(path==='/mes-annonces') page = <MyAnnouncementsPage/>;
 else if(path==='/agences-livraison') page = <DeliveryAgencies/>;
 else if(path==='/annonces') page = <Directory type="annonces"/>;
 else if(path.startsWith('/annuaire/')) page = <Directory type={path.split('/')[2]||''}/>;
 else if(['/conditions-generales','/mentions-legales','/confidentialite'].includes(path)) page = <LegalDocuments/>;
 else if(path==='/messages') page = <Messages/>;
 else if(path==='/recherche') page = <SearchPage/>;
 else if(path==='/pro') page = <ProfessionalOverview/>;
 else if(path==='/pro/commandes') page = <ProfessionalOrders/>;
 else if(path==='/pro/messages') page = <Messages/>;
 else if(path==='/pro/finances') page = <ProfessionalFinance/>;
 else if(path==='/pro/abonnement') page = <ProfessionalSubscription/>;
 else if(path==='/pro/parametres') page = <ProfessionalSettings/>;
 else if(path==='/pro/livraisons') page = <ProfessionalDeliveryManager/>;
 else if(path==='/pro/livraisons/agence') page = <DeliveryAgency/>;
 else if(path==='/pro/livraisons/boutique') page = <BoutiqueDeliveryManager/>;
 else if(path==='/pro/livraisons/restaurant') page = <RestaurantDeliveryManager/>;
 else if(path==='/pro/reservations') page = <RestaurantReservationManager/>;
 else if(path==='/pro/vitrine') page = <StorefrontBuilder/>;
 else if(path==='/pro/catalogue') page = <BoutiqueCatalogManager/>;
 else if(path==='/pro/hotel') page = <HotelDashboard/>;
 else if(/^\/restaurant\/[^/]+\/reserver$/.test(path)) page = <RestaurantReservation/>;
 else if(/^\/hotel\/[^/]+\/reserver$/.test(path)) page = <HotelBooking/>;
 else if(path==='/livraison') page = <DeliveryOptions/>;
 else if(path==='/panier') page = <Cart/>;
 else if(path==='/checkout') page = <Checkout/>;
 else if(path.startsWith('/commande/')) page = <Order/>;
 else if(path.startsWith('/livraison/')) page = <Delivery/>;
 else if(path.startsWith('/annonce/')) page = <AnnonceDetail/>;
 else if(path.startsWith('/produit/')) page = <PublicProduct productId={path.split('/')[2] || ''}/>;
 else if(/^\/vitrine\/[^/]+$/.test(path)) page = <PublicStorefront slug={path.split('/')[2]}/>;
 else if(/^\/boutique\/[^/]+$/.test(path)) page = <PublicStorefront type="boutique" spaceId={path.split('/')[2]}/>;
 else if(/^\/restaurant\/[^/]+$/.test(path)) page = <PublicStorefront type="restaurant" spaceId={path.split('/')[2]}/>;
 else if(/^\/hotel\/[^/]+$/.test(path)) page = <PublicStorefront type="hotel" spaceId={path.split('/')[2]}/>;
 else page = <Home/>;
 return <PageTransition key={path}>{page}</PageTransition>;
}
